import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {gzipSync} from 'node:zlib';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const input=process.argv[2]||path.join(root,'academy-majors-2026.raw.json');
const raw=JSON.parse(fs.readFileSync(input,'utf8').replace(/^\uFEFF/,''));
const rows=raw.resultList;
if(!Array.isArray(rows)||!rows.length||rows.length!==Number(rows[0].total_count))throw new Error('Source count mismatch');
if(raw.pramMap?.svyYr!=='2026')throw new Error('Unexpected year');
if(rows.some(r=>!['01','02'].includes(r.schl_div_cd)))throw new Error('Unexpected school scope');
const text=v=>String(v??'').trim().replace(/\s+/g,' ');
const fields=['schl_id','schl_nm','psbs_div_nm','mjr_nm','schl_mjr_id','schl_mjr_stat_nm','srs_lclft_nm','srs_mclft_nm','srs_sclft_nm','mjr_area_nm','schl_knd_nm','dght_div_nm'];
const records=rows.map(r=>Object.fromEntries(fields.map(k=>[k,text(r[k])])));
const active=records.filter(r=>r.schl_mjr_stat_nm!=='폐과');
const metadata={title:'대학알리미 2026 키워드별 학과정보',source:'https://www.academyinfo.go.kr/mjrinfo/mjrinfo0450/doInit.do',provider:'교육부·한국대학교육협의회 대학알리미',licenseReference:'https://www.data.go.kr/data/15119002/fileData.do',year:2026,retrievedAt:new Date().toISOString(),scope:'대학·전문대학 구분 02,01. 대학원 제외. 폐과 기록 보존.',sourceCount:rows.length,activeRecords:active.length,activeNames:new Set(active.map(r=>r.mjr_nm)).size,activeSchools:new Set(active.map(r=>r.schl_id)).size,coverage:'해당 연도 대학알리미 공개 검색 범위이며 현재 모든 대학의 모집단위와 일치함을 보장하지 않습니다.'};
fs.mkdirSync(path.join(root,'data'),{recursive:true});
fs.writeFileSync(path.join(root,'data','university-departments.json'),JSON.stringify({metadata,records}));
fs.writeFileSync(path.join(root,'data','academy-2026-source.json.gz'),gzipSync(fs.readFileSync(input)));
console.log(JSON.stringify(metadata,null,2));
